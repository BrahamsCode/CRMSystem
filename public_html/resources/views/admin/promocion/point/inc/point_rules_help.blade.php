<p>※ポイント発行ルールは<span style="font-weight: bold; color: #113366;">リストの上位にあるものほど優先</span>されます。<br />

<span style="font-weight: bold;">【基本概念】</span><br />
・ルールは、全店舗で設定しているものより、各店舗で設定しているルールが優先されます。<br />
・ルール優先度は区分によって優先順位が決定されます。<br />
・同じ区分で指定されて、かつ時間が重複しているルールに関しても、リストの上位に存在するルールの方が優先されます。<br />
・区分自体の優先度を変更する事はできませんが、同じ区分に収まったルールどうしは、設定の更新日付でリストが上下します。（更新日付が近いほど上位）</p>
<span style="font-weight: bold;">【基本優先順位】</span>
<ol style="width: 15em; padding: 5px 10px; border: 1px dotted #999;">
<li style="list-style:decimal inside none;">日付指定</li>
<li style="list-style:decimal inside none;">毎月○○日指定</li>
<li style="list-style:decimal inside none;">期間指定</li>
<li style="list-style:decimal inside none;">曜日指定</li>
<li style="list-style:decimal inside none;">時間指定</li>
</ol>
